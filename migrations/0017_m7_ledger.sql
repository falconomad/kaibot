-- 0017: Engine v3 S77 (#117, decision 15 section 3): the ledger and the local journal.
--
-- APPLY BEFORE the engine with the journal (PR for #117) starts on paper. Safe to apply while today's engine runs:
-- every change is additive, and rows written without the new columns keep working.
--
-- The engine now writes everything to a local append-only journal first (data/live/journal.sqlite) and replicates
-- to these tables asynchronously, so Supabase is no longer on the order path (audit D5, H2). Replication must be
-- idempotent and must keep the references between rows, so:
--
-- 1. run, signal, "order" and trade take the engine's own ids (the engine assigns them from 1,000,000,001 up, far
--    above anything the sequences hand out): the identity columns become `generated by default`.
-- 2. segment, gate_run, fill, halt, event and gate_report get `jseq` (the journal's sequence number, unique), so a
--    row sent twice (an answer lost, or a rebuild of the database from the journal) is refused as a duplicate,
--    which the engine counts as "already there".
-- 3. The ledger's daily mark-to-market rows: kaibot.ledger_day (one per run and session) and kaibot.ledger_position
--    (one per run, session, strategy and symbol: two rules can hold the same stock).
-- 4. Compatibility: kaibot.daily_result_mtm is daily_result with the ledger's start and close equity; kb_report's
--    start equity reads it (yesterday's mark-to-market close; the old "pot + realised results" for sessions closed
--    before the ledger existed). Every other dashboard RPC is unchanged and keeps working.
-- 5. The RPC contract for the multi-day dashboard (S90, docs/ops/ledger.md): kb_book and kb_equity_series.

-- ---------- 1. engine-assigned ids ----------
alter table kaibot.run alter column id set generated by default;
alter table kaibot.signal alter column id set generated by default;
alter table kaibot."order" alter column id set generated by default;
alter table kaibot.trade alter column id set generated by default;

-- ---------- 2. idempotent replication ----------
alter table kaibot.segment add column if not exists jseq bigint unique;
alter table kaibot.gate_run add column if not exists jseq bigint unique;
alter table kaibot.fill add column if not exists jseq bigint unique;
alter table kaibot.halt add column if not exists jseq bigint unique;
alter table kaibot.event add column if not exists jseq bigint unique;
alter table kaibot.gate_report add column if not exists jseq bigint unique;

-- ---------- 3. the ledger's daily close ----------
create table if not exists kaibot.ledger_day (
  run_id             bigint not null references kaibot.run(id),
  session            date not null,
  start_equity       numeric(14,2) not null,  -- the previous close (or the pot): the base of the day's stop
  close_equity       numeric(14,2) not null,  -- what the engine sizes on: reported results + open positions at the mark
  close_equity_venue numeric(14,2) not null,  -- cash + open positions at the mark (the broker's view)
  cash               numeric(14,2) not null,
  invested           numeric(14,2) not null,  -- sum of qty x mark
  realized_venue     numeric(14,2) not null,
  pnl_venue          numeric(14,2) not null,  -- as daily_result
  pnl_shadow         numeric(14,2) not null,
  dividends          numeric(14,2) not null default 0,
  gross              double precision not null,  -- invested / close_equity_venue
  overnight          double precision not null,  -- the part held over this close (all of it, at the close)
  positions          integer not null,
  reconciled         jsonb,                   -- {ok, positions: {symbol: {ledger, broker}}, cash_diff, tolerance, ts}
  ts                 timestamptz not null,
  primary key (run_id, session)
);
alter table kaibot.ledger_day enable row level security;

create table if not exists kaibot.ledger_position (
  run_id          bigint not null references kaibot.run(id),
  session         date not null,
  strategy        text not null,
  symbol          text not null,
  qty             numeric(14,4) not null,
  avg_cost        numeric(14,4) not null,   -- per share, buy fees included
  mark            numeric(14,4) not null,   -- the close (priced = false: no price, held at the last mark or cost)
  priced          boolean not null,
  opened_session  date,
  dividends       numeric(14,2) not null default 0,
  stop_px         numeric(14,4),
  stop_state      text not null check (stop_state in ('resting', 'missing', 're-arming')),
  primary key (run_id, session, strategy, symbol)
);
alter table kaibot.ledger_position enable row level security;

-- ---------- 4. compatibility ----------
create or replace view kaibot.daily_result_mtm with (security_invoker = true) as
select d.*,
  coalesce(l.start_equity, r.amount_usd + coalesce((select sum(x.pnl_reported) from kaibot.daily_result x
    where x.run_id = d.run_id and x.session < d.session), 0)) as start_equity,
  coalesce(l.close_equity, r.amount_usd + coalesce((select sum(x.pnl_reported) from kaibot.daily_result x
    where x.run_id = d.run_id and x.session <= d.session), 0)) as close_equity,
  l.close_equity_venue, l.cash, l.invested, l.dividends, l.gross, l.positions as open_positions,
  (l.run_id is not null) as marked
from kaibot.daily_result d
join kaibot.run r on r.id = d.run_id
left join kaibot.ledger_day l on l.run_id = d.run_id and l.session = d.session;
revoke all on kaibot.daily_result_mtm from public, anon, authenticated;
grant select on kaibot.daily_result_mtm to service_role;

-- kb_report as in 0007, except start_equity: the ledger's (yesterday's mark-to-market close) where it exists.
create or replace function public.kb_report(p_run bigint, p_session date default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare d date; lo timestamptz; hi timestamptz;
begin
  if not kaibot.is_owner() then raise exception 'not authorised' using errcode = '42501'; end if;
  d := coalesce(p_session, (select max(x.session) from kaibot.daily_result x where x.run_id = p_run));
  if d is null then
    return jsonb_build_object('session', null, 'sessions', '[]'::jsonb);
  end if;
  lo := d::timestamp at time zone 'America/New_York';
  hi := (d + 1)::timestamp at time zone 'America/New_York';
  return jsonb_build_object(
    'session', d,
    'sessions', coalesce((select jsonb_agg(x.session order by x.session desc)
      from kaibot.daily_result x where x.run_id = p_run), '[]'::jsonb),
    'day', (select jsonb_build_object('pnl', x.pnl_reported, 'pnl_venue', x.pnl_venue, 'pnl_shadow', x.pnl_shadow,
        'spy_ret', x.spy_ret, 'cash_ret', x.cash_ret, 'trades', x.trades)
      from kaibot.daily_result x where x.run_id = p_run and x.session = d),
    'start_equity', coalesce(
      (select m.start_equity from kaibot.daily_result_mtm m where m.run_id = p_run and m.session = d),
      (select r.amount_usd + coalesce(sum(x.pnl_reported), 0) from kaibot.run r
        left join kaibot.daily_result x on x.run_id = r.id and x.session < d where r.id = p_run group by r.amount_usd)),
    'trades', coalesce((select jsonb_agg(jsonb_build_object('id', t.id, 'strategy', t.strategy, 'symbol', t.symbol,
        'entry_ts', t.entry_ts, 'exit_ts', t.exit_ts, 'qty', t.qty, 'entry_px', t.entry_px, 'exit_px', t.exit_px,
        'pnl_usd', t.pnl_usd, 'risk_usd', t.risk_usd, 'exit_reason', t.exit_reason) order by t.entry_ts)
      from kaibot.trade t where t.run_id = p_run and t.entry_ts >= lo and t.entry_ts < hi), '[]'::jsonb),
    'signals', (select jsonb_build_object(
        'live', count(*) filter (where s.mode = 'live'),
        'approved', count(*) filter (where s.mode = 'live' and g.approved),
        'shadow', count(*) filter (where s.mode = 'shadow'))
      from kaibot.signal s left join kaibot.gate_run g on g.signal_id = s.id
      where s.run_id = p_run and s.ts >= lo and s.ts < hi),
    'vetoes', coalesce((select jsonb_agg(jsonb_build_object('reason', v.reason, 'n', v.n) order by v.n desc) from (
        select coalesce(s.rules_veto, 'gate: ' || coalesce(g.binding, 'qty 0')) as reason, count(*) as n
        from kaibot.signal s left join kaibot.gate_run g on g.signal_id = s.id
        where s.run_id = p_run and s.mode = 'live' and s.ts >= lo and s.ts < hi
          and (s.rules_veto is not null or not coalesce(g.approved, false))
        group by 1) v), '[]'::jsonb),
    'shadow', coalesce((select jsonb_agg(jsonb_build_object('strategy', s.strategy, 'symbol', s.symbol, 'ts', s.ts,
        'veto', s.rules_veto, 'pnl_usd', (s.features->'counterfactual'->>'pnl_usd')::numeric,
        'r', (s.features->'counterfactual'->>'r_multiple')::numeric) order by s.ts)
      from kaibot.signal s where s.run_id = p_run and s.mode = 'shadow' and s.ts >= lo and s.ts < hi), '[]'::jsonb),
    'halts', coalesce((select jsonb_agg(jsonb_build_object('kind', h.kind, 'reason', h.reason, 'ts', h.ts) order by h.ts)
      from kaibot.halt h where (h.run_id = p_run or h.run_id is null) and h.ts >= lo and h.ts < hi), '[]'::jsonb)
  );
end $$;

-- ---------- 5. the multi-day dashboard (contract: docs/ops/ledger.md) ----------
-- kb_book: the book at a session's close (default: the latest). Shape = apps/web/src/lib/multiday.ts MultidayBook,
-- with the differences listed in docs/ops/ledger.md. Money in dollars, fractions 0..1, sessions YYYY-MM-DD (ET).
create or replace function public.kb_book(p_run bigint, p_session date default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare d date; l kaibot.ledger_day; prev numeric; div numeric;
begin
  if not kaibot.is_owner() then raise exception 'not authorised' using errcode = '42501'; end if;
  d := coalesce(p_session, (select max(x.session) from kaibot.ledger_day x where x.run_id = p_run));
  select * into l from kaibot.ledger_day x where x.run_id = p_run and x.session = d;
  if l.run_id is null then
    return jsonb_build_object('run_id', p_run, 'session', null, 'mtm', null, 'positions', '[]'::jsonb,
      'exposure', null, 'reconciled', null);
  end if;
  select coalesce(sum(x.dividends), 0) into div from kaibot.ledger_day x where x.run_id = p_run and x.session <= d;
  return jsonb_build_object(
    'run_id', p_run,
    'session', d,
    'mtm', jsonb_build_object(
      'ts', l.ts, 'at_close', true, 'cash', l.cash, 'invested', l.invested, 'equity', l.close_equity_venue,
      'equity_reported', l.close_equity,
      'start_equity', (select r.amount_usd from kaibot.run r where r.id = p_run),
      'prev_close_equity', l.start_equity, 'open_equity', null, 'dividends_to_date', div),
    'positions', coalesce((select jsonb_agg(jsonb_build_object(
        'rule', p.strategy, 'symbol', p.symbol, 'qty', p.qty, 'avg_cost', p.avg_cost,
        'last', case when p.priced then p.mark end, 'last_ts', case when p.priced then l.ts end,
        'mark', p.mark, 'opened_session', p.opened_session, 'dividends', p.dividends,
        'stop', case when p.stop_px is null then null
                     else jsonb_build_object('price', p.stop_px, 'state', p.stop_state) end)
      order by p.strategy, p.symbol)
      from kaibot.ledger_position p where p.run_id = p_run and p.session = d), '[]'::jsonb),
    'exposure', jsonb_build_object(
      'gross', l.gross, 'overnight', l.overnight, 'cap', null,
      'by_rule', coalesce((select jsonb_agg(jsonb_build_object('rule', b.strategy, 'value', b.value,
          'share', case when l.close_equity_venue > 0 then b.value / l.close_equity_venue else 0 end)
          order by b.value desc)
        from (select p.strategy, sum(p.qty * p.mark) as value from kaibot.ledger_position p
              where p.run_id = p_run and p.session = d group by p.strategy) b), '[]'::jsonb),
      'market_filter', '[]'::jsonb),
    'reconciled', case when l.reconciled ? 'ok' and l.reconciled->>'ok' is not null
      then jsonb_build_object('ok', (l.reconciled->>'ok')::boolean, 'ts', l.reconciled->>'ts',
                              'positions', l.reconciled->'positions', 'cash_diff', l.reconciled->'cash_diff') end
  );
end $$;

-- kb_equity_series: the pot marked to market, one point per session, oldest first (p_from / p_to inclusive).
create or replace function public.kb_equity_series(p_run bigint, p_from date default null, p_to date default null)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not kaibot.is_owner() then raise exception 'not authorised' using errcode = '42501'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object(
      'session', m.session, 'start_equity', m.start_equity, 'close_equity', m.close_equity,
      'close_equity_venue', m.close_equity_venue, 'cash', m.cash, 'invested', m.invested,
      'dividends', coalesce(m.dividends, 0), 'pnl', m.pnl_reported, 'pnl_venue', m.pnl_venue,
      'pnl_shadow', m.pnl_shadow, 'gross', m.gross, 'positions', m.open_positions, 'marked', m.marked)
    order by m.session)
    from kaibot.daily_result_mtm m
    where m.run_id = p_run and (p_from is null or m.session >= p_from) and (p_to is null or m.session <= p_to)),
    '[]'::jsonb);
end $$;

revoke all on function public.kb_book(bigint, date), public.kb_equity_series(bigint, date, date) from public, anon;
grant execute on function public.kb_book(bigint, date), public.kb_equity_series(bigint, date, date) to authenticated;
