def test_the_targets_have_teeth():
    """A decoder that breaks its property is caught: a planted bug in the journal's checksum check."""
    from kaibot.engine import journal

    real = journal.check_entry
    try:
        journal.check_entry = lambda *a, **k: None
        caught = 0
        for p in _corpus("journal_entries"):
            try:
                targets.journal_entries(p.read_bytes())
            except targets.Violation:
                caught += 1
        assert caught, "no corpus input notices a journal whose checksums are never checked"
    finally:
        journal.check_entry = real


# ---------------------------------------------------------------- the engine defects found (strict xfails)
def test_a_damaged_kind_index_does_not_hide_entries_543():
    """#543 fixed: the journal's structure is checked at open (`pragma integrity_check`): refused, exit code 4."""
    from kaibot.engine.journal import Journal, JournalCorrupt

    with tempfile.TemporaryDirectory(prefix="kb-fuzz-") as td:
        p = Path(td) / "journal.sqlite"
        j = Journal(p)
        for i in range(3):
            j.append("fill", {"coid": f"c{i}"})
        j.close()
        db = sqlite3.connect(p)
        root = db.execute("select rootpage from sqlite_master where name='entry_kind_seq'").fetchone()[0]
        psize = db.execute("pragma page_size").fetchone()[0]
        db.close()
        raw = bytearray(p.read_bytes())
        off = (root - 1) * psize
        raw[off + raw[off:off + psize].find(b"fill") + 1] = ord("x")  # 'fill' -> 'fxll' in the index only
        p.write_bytes(bytes(raw))
        try:
            j = Journal(p)
        except (JournalCorrupt, sqlite3.DatabaseError):
            return  # refused at start: what the issue asks for
        try:
            assert len(j.entries(kinds=("fill",))) == len([e for e in j.entries() if e[2] == "fill"]) == 3
            assert j.count(("fill",)) == 3
        finally:
            j.close()


def test_a_lost_last_entry_is_refused_at_open_590():
    """#590 (nightly fuzz input `corpus/journal_file/entry-leaf-cell-count-damaged-590`): one flipped bit in the
    cell count of the entry table's leaf page (3 -> 2) drops the last entry from the table. The checksum chain
    cannot see a lost tail, so the journal opened with 2 entries of 3 before #543's structure check; now the table
    no longer matches its kind index and the journal is refused at open (exit code 4)."""
    from kaibot.engine.journal import Journal, JournalCorrupt

    with tempfile.TemporaryDirectory(prefix="kb-fuzz-") as td:
        p = Path(td) / "journal.sqlite"
        j = Journal(p)
        for i in range(3):
            j.append("fill", {"coid": f"c{i}"})
        j.db.execute("pragma wal_checkpoint(truncate)")
        j.close()
        db = sqlite3.connect(p)
        root = db.execute("select rootpage from sqlite_master where name='entry'").fetchone()[0]
        psize = db.execute("pragma page_size").fetchone()[0]
        db.close()
        raw = bytearray(p.read_bytes())
        head = (root - 1) * psize + (100 if root == 1 else 0)
        assert raw[head] == 0x0D and raw[head + 3:head + 5] == b"\x00\x03"  # a table leaf holding the 3 entries
        raw[head + 4] ^= 1  # 3 cells -> 2: the last entry is gone from the table, still in the index
        p.write_bytes(bytes(raw))
        with pytest.raises(JournalCorrupt, match="damaged"):
            Journal(p)


def _om_with_activity(act: dict):
    from kaibot.broker.protocol import OrderRequest
    from kaibot.engine.journal import Journal
    from kaibot.engine.ledger import LEDGER_KINDS, Ledger
    from kaibot.engine.orders import OrderManager

    now = datetime(2026, 8, 3, 19, 50, tzinfo=UTC)

    class Venue:
        acts: list = []

        def submit(self, req):
            return {"id": "o1", "client_order_id": req.client_order_id, "status": "new", "qty": "10",
                    "filled_qty": "0"}

        def order(self, oid):
            return {"id": "o1", "status": "filled", "qty": "10", "filled_qty": "10"}

        def activities(self, after=None, types=("FILL",)):
            return self.acts

    v, j = Venue(), Journal(":memory:", now=lambda: now)
    j.append("run", {"run_id": 1, "amount": 10_000.0})
    om = OrderManager(v, j, lambda: now, run_id=1)
    om.submit(OrderRequest("B", "buy", 10, client_order_id=om.next_coid(1, "s", "B", "2026-08-03", "buy")),
              strategy="s", purpose="buy", session="2026-08-03")
    v.acts = [{"id": "a1", "order_id": "o1", "symbol": "B", "transaction_time": "2026-08-03T19:50:01Z", **act}]
    with contextlib.suppress(ValueError, TypeError, KeyError):  # refused loudly: fine
        om.sync()
    return Ledger.fold(e for e in j.entries() if e[2] in LEDGER_KINDS).book(1)


@pytest.mark.parametrize("act", [{"side": "BUY", "qty": "10", "price": "100"},
                                 {"side": "buy", "qty": "10", "price": "NaN"},
                                 {"side": "buy", "qty": "-10", "price": "100"},
                                 {"side": "buy", "qty": "1e308", "price": "2.5"}],
                         ids=["side BUY", "price NaN", "qty -10", "value beyond a float 656"])
def test_a_malformed_fill_activity_is_not_booked_545(act):
    """#545 fixed: broker/payloads.fill refuses it; the order manager keeps it as a fill it cannot attribute.
    #656 (nightly fuzz input `corpus/broker_payloads/fill-value-overflow-656`): 1e308 shares at 2.5 are each finite,
    their value is not; booked, the ledger's cash was -inf. Refused the same way now."""
    book = _om_with_activity(act)
    assert book.cash == 10_000.0 and not book.qty_by_symbol(), \
        f"booked: cash {book.cash}, shares {book.qty_by_symbol()}"


def test_a_non_finite_dividend_is_not_booked_545():
    """#545 (first comment) fixed: a dividend whose net_amount is not finite is not an action."""
    from kaibot.engine.ledger import actions_from_activities

    acts = actions_from_activities([{"activity_type": "DIV", "symbol": "B", "net_amount": "NaN", "id": "d1",
                                     "date": "2026-08-03"}], {"B": 10.0}, {"B": 10.0})
    assert acts == [] or all(a.amount == a.amount for a in acts)  # NaN != NaN
