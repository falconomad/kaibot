def test_a_marked_answer_is_a_copy_and_a_good_one_is_passed_as_it_is():
    good, bad = _act(), _act(price="NaN")
    out = payloads.mark_activities([good, bad, {"activity_type": "DIV", "net_amount": "NaN"}])
    assert out[0] is good and INVALID not in good and out[1][INVALID] and INVALID not in bad
    assert INVALID not in out[2]  # other activity types: their own decoders
    assert payloads.mark_order({"qty": "10", "filled_qty": "-1"})[INVALID]
    with pytest.raises(PayloadError):
        payloads.fill(out[1])  # a marked row is refused again downstream


def test_the_simulators_own_fills_and_orders_pass_the_checks():
    """The simulator's payloads are what the live path accepts (else a test could pass on a payload Alpaca's
    adapter would refuse): a filled buy and a partly filled one, their order views and their activities, unmarked."""
    from test_order_manager import DAY, mkt, run, venue

    b, clock = venue()
    b.script.fills("A", [50.0])
    o1 = b.submit(mkt("A", qty=100, attempt=1))
    o2 = b.submit(mkt("B", qty=40, attempt=1))
    run(b, clock, 31, 33, DAY)
    views = [b.order(o1["id"]), b.order(o2["id"]), *b.open_orders(), b.order_by_client_id(o2["client_order_id"])]
    acts = b.activities()
    assert acts and not [a for a in acts if a.get(INVALID)] and not [v for v in views if v.get(INVALID)]


