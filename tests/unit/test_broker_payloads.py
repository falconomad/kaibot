NOW = datetime(2026, 8, 3, 19, 50, tzinfo=UTC)
ANY = st.one_of(st.none(), st.booleans(), st.integers(), st.floats(allow_nan=True, allow_infinity=True),
                st.text(max_size=12), st.lists(st.integers(), max_size=2), st.dictionaries(st.text(max_size=3),
                                                                                           st.integers(), max_size=2))
NUMERIC_TEXT = st.one_of(st.floats(allow_nan=True, allow_infinity=True).map(repr),
                         st.sampled_from(["NaN", "inf", "-inf", "-10", "0", "1e309", " 5", "5 ", "1_0", "", "x"]))


def _ok(x) -> bool:
    return isinstance(x, float) and math.isfinite(x)


# ---------------------------------------------------------------- properties of the decoders
@settings(max_examples=400, deadline=None)
@given(a=st.fixed_dictionaries({}, optional={"id": ANY, "order_id": ANY, "symbol": ANY, "side": st.one_of(
    ANY, st.sampled_from(["buy", "sell", "BUY", "Sell", "sell_short", " buy"])), "qty": st.one_of(ANY, NUMERIC_TEXT),
    "price": st.one_of(ANY, NUMERIC_TEXT), "fees": st.one_of(ANY, NUMERIC_TEXT), "transaction_time": ANY}))
def test_a_fill_is_either_refused_or_bookable(a):
    """Whatever the venue sends, `fill` raises PayloadError (and nothing else) or gives a fill the ledger can book:
    side exactly buy or sell, quantity and price finite and above zero, fees finite and not negative."""
    try:
        f = payloads.fill(a)
    except PayloadError:
        return
    assert f["side"] in ("buy", "sell")
    assert _ok(f["qty"]) and f["qty"] > 0 and _ok(f["price"]) and f["price"] > 0
    assert _ok(f["fees"]) and f["fees"] >= 0
    assert f["id"] and f["order_id"] and f["symbol"]


@settings(max_examples=300, deadline=None)
@given(o=st.fixed_dictionaries({}, optional={"qty": st.one_of(ANY, NUMERIC_TEXT),
                                             "filled_qty": st.one_of(ANY, NUMERIC_TEXT)}),
       qty=st.one_of(st.none(), st.floats(min_value=0.5, max_value=1e6)))
def test_an_order_view_is_either_refused_or_has_a_readable_fill(o, qty):
    try:
        payloads.order(o, qty)
    except PayloadError:
        return
    f = o.get("filled_qty")
    filled = 0.0 if f in (None, "") else float(f)
    assert math.isfinite(filled) and filled >= 0
    q = float(o["qty"]) if o.get("qty") not in (None, "") else qty
    assert q is None or filled <= q + 1e-9


@settings(max_examples=200, deadline=None)
@given(v=st.one_of(ANY, NUMERIC_TEXT))
def test_a_dividend_amount_is_finite_or_refused(v):
    try:
        x = payloads.dividend_amount({"net_amount": v})
    except PayloadError:
        return
    assert _ok(x)


@pytest.mark.parametrize("a, ok", [
    ({"side": "buy", "qty": "10", "price": "100.5"}, True),
    ({"side": "sell", "qty": 3, "price": 2.5, "fees": "0.01"}, True),
    ({"side": "BUY", "qty": "10", "price": "100"}, False),  # exactly as documented: no guess at "buy"
    ({"side": "sell_short", "qty": "10", "price": "100"}, False),  # the engine never shorts
    ({"side": "buy", "qty": "-10", "price": "100"}, False),
    ({"side": "buy", "qty": "10", "price": "NaN"}, False),
    ({"side": "buy", "qty": "10", "price": "100", "fees": "-1"}, False),
    ({"side": "buy", "qty": True, "price": "100"}, False),
    ({"side": "buy", "qty": "10", "price": "100", "transaction_time": "yesterday"}, False),
])
def test_the_fill_cases(a, ok):
    a = {"id": "a1", "order_id": "o1", "symbol": "B", "transaction_time": "2026-08-03T19:50:01Z", **a}
    if ok:
        assert payloads.fill(a)["side"] == a["side"]
    else:
        with pytest.raises(PayloadError):
            payloads.fill(a)


# ---------------------------------------------------------------- the order manager and the ledger
class Venue:
    def __init__(self, view=None):
        self.acts: list = []
        self.view = view or {"id": "o1", "status": "filled", "qty": "10", "filled_qty": "10"}

    def submit(self, req):
        return {"id": "o1", "client_order_id": req.client_order_id, "status": "new", "qty": "10", "filled_qty": "0"}

    def order(self, oid):
        return self.view

    def order_by_client_id(self, coid):
        return self.view

    def open_orders(self):
        return []

    def activities(self, after=None, types=("FILL",)):
        return self.acts


def _om(venue):
    j = Journal(":memory:", now=lambda: NOW)
    j.append("run", {"run_id": 1, "amount": 10_000.0})
    om = OrderManager(venue, j, lambda: NOW, run_id=1)
    r = om.submit(OrderRequest("B", "buy", 10, client_order_id=om.next_coid(1, "s", "B", "2026-08-03", "buy")),
                  strategy="s", purpose="buy", session="2026-08-03")
    return om, j, r


def _book(j):
    return Ledger.fold(e for e in j.entries() if e[2] in LEDGER_KINDS).book(1)


def _act(**kw):
    return {"id": "a1", "order_id": "o1", "symbol": "B", "side": "buy", "qty": "10", "price": "100",
            "transaction_time": "2026-08-03T19:50:01Z", **kw}


def test_a_good_fill_is_booked():
    v = Venue()
    om, j, _ = _om(v)
    v.acts = [_act()]
    om.sync()
    b = _book(j)
    assert b.qty_by_symbol() == {"B": 10.0} and b.cash == 9_000.0 and not om.invalid


@pytest.mark.parametrize("bad", [{"side": "BUY"}, {"price": "NaN"}, {"qty": "-10"}, {"qty": "inf"},
                                 {"fees": "nan"}, {"side": "sell_short"}, {"symbol": "C"}])
def test_a_refused_fill_is_not_booked_and_blocks_its_symbol(bad):
    """Never booked; kept as a fill the manager cannot attribute (the reconciliation's foreign_fill blocks buys in
    the symbol), counted, and not read as "the activities could not be read" (`errors`)."""
    v = Venue()
    om, j, r = _om(v)
    v.acts = [_act(**bad)]
    om.sync()
    b = _book(j)
    assert b.cash == 10_000.0 and not b.qty_by_symbol()
    assert "a1" in om.foreign and om.foreign["a1"][INVALID] and om.invalid_count >= 1 and "a1" in om.invalid
    assert not [e for e in om.errors if "activities" in e[1]]
    assert r.booked == 0 and r.cum == 10.0 and r.coid in om.settling  # also an "unbooked" difference


def test_an_order_view_with_an_unreadable_fill_is_not_taken():
    """The fuzz case: a -inf filled quantity. The order the venue had not confirmed stays unknown (blocks B)."""
    v = Venue(view={"id": "o1", "status": "filled", "qty": "10", "filled_qty": "-inf"})
    j = Journal(":memory:", now=lambda: NOW)
    om = OrderManager(v, j, lambda: NOW, run_id=1)
    v.submit = lambda req: {"id": "o1", "client_order_id": req.client_order_id, "status": "new", "qty": "10",
                            "filled_qty": "-inf"}
    r = om.submit(OrderRequest("B", "buy", 10, client_order_id=om.next_coid(1, "s", "B", "2026-08-03", "buy")),
                  strategy="s", purpose="buy", session="2026-08-03")
    assert r.state is St.UNKNOWN and r.cum == 0.0 and om.blocked("B")
    om.sync()
    assert r.state is St.UNKNOWN and r.cum == 0.0
    assert all(math.isfinite(float(b["cum"])) for *_, k, b in j.entries() if k == "om_state" and "cum" in b)


def test_a_view_above_the_orders_quantity_is_not_taken():
    v = Venue(view={"id": "o1", "status": "filled", "qty": "10", "filled_qty": "11"})
    om, _, r = _om(v)
    om.sync()
    assert r.state is St.ACCEPTED and r.cum == 0.0 and "order:" + r.coid in om.invalid


def test_the_ledger_never_books_a_fill_entry_with_another_side():
    """An entry written by an older release or by hand: anything but "buy" was booked as a sale."""
    lg = Ledger()
    lg.apply("run", {"run_id": 1, "amount": 1_000.0})
    for side, qty, px in (("BUY", 10.0, 10.0), ("buy", -5.0, 10.0), ("buy", 1.0, float("nan"))):
        lg.apply("fill", {"run_id": 1, "strategy": "s", "symbol": "B", "side": side, "qty": qty, "px": px})
    assert lg.book(1).cash == 1_000.0 and not lg.book(1).qty_by_symbol()


def test_a_dividend_that_is_not_finite_is_not_an_action():
    rows = [{"activity_type": "DIV", "symbol": "B", "net_amount": v, "id": f"d{i}", "date": "2026-08-03"}
            for i, v in enumerate(("NaN", "inf", "x", "1.5", "-0.3"))]
    acts = actions_from_activities(rows, {"B": 10.0}, {"B": 10.0})
    assert [a.amount for a in acts] == [1.5, -0.3]


