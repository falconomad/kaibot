def test_a_refused_fill_with_an_unreadable_time_does_not_stop_the_reads():
    """One refused activity whose time cannot be read was kept in `foreign`, and the window of every later read
    was computed from it: ValueError on every sync, so no later fill (a sale, a flatten) was booked again."""
    v = Venue()
    om, j, r = _om(v)
    v.acts = [_act(id="a0", transaction_time="yesterday")]
    om.sync()
    assert "a0" in om.foreign and om.foreign["a0"][INVALID]
    v.acts = [_act(id="a0", transaction_time="yesterday"), _act(id="a1")]
    om.sync()
    om.sync()
    assert r.booked == 10.0 and _book(j).qty_by_symbol() == {"B": 10.0}


def test_a_refused_fill_the_owner_accepted_no_longer_pins_the_reads():
    from types import SimpleNamespace

    from kaibot.engine import live_daily as ld

    j = Journal(":memory:", now=lambda: NOW)
    om = SimpleNamespace(foreign={"a0": {**_act(id="a0", side="BUY"), INVALID: "side"},
                                  "a9": {**_act(id="a9", side="BUY"), INVALID: "side"}})
    j.append("reconcile_resolved", {"foreign": ["a0"]})
    me = SimpleNamespace(om=om, journal=j, now=lambda: NOW, known_order_ids=lambda: set())
    ld.LiveDaily._prune(me)
    assert set(om.foreign) == {"a9"}  # the accepted one goes; the other still blocks its symbol


def _engine_for(rows=(), entries=()):
    from types import SimpleNamespace

    from kaibot.engine import core

    j = Journal(":memory:", now=lambda: NOW)
    for k, b in entries:
        j.append(k, b)
    events = []
    e = SimpleNamespace(journal=j, run={"id": 1}, _rid=lambda: 1,
                        store=SimpleNamespace(event=lambda kind, body, rid=None: events.append((kind, body))),
                        broker=SimpleNamespace(activities=lambda after=None, types=("FILL",): list(rows)))
    e._payload_refused = lambda key, why: core.Engine._payload_refused(e, key, why)
    return core, e, events


def test_a_dividend_payment_that_is_not_a_number_does_not_close_its_accrual():
    acc = {"ref": "d1", "symbol": "B", "ex_date": "2026-08-01", "pay_date": "2026-08-03", "amount": 12.5}
    core, e, events = _engine_for(entries=[("div_accrual", acc)])
    rows = [{"activity_type": "DIV", "id": "x1", "symbol": "B", "date": "2026-08-03", "net_amount": "NaN"}]
    out = core.Engine._match_dividend_payments(e, rows)
    assert out == [] and not e.journal.entries(kinds=("div_paid",))  # neither matched nor booked
    assert [k for k, b in events] == ["multi_day_error"] and events[0][1]["step"] == "broker_payload"
    rows = [{"activity_type": "DIV", "id": "x2", "symbol": "B", "date": "2026-08-03", "net_amount": "12.50"}]
    assert core.Engine._match_dividend_payments(e, rows) == [] and e.journal.entries(kinds=("div_paid",))


def test_a_refused_activity_adds_no_fee():
    rows = [_act(id="f1", fees="0.02"), _act(id="f2", fees="nan"), _act(id="f3", order_id="o2", fees="0.5")]
    core, e, events = _engine_for(rows=rows)
    assert core.Engine._venue_fees(e, "o1", "2026-08-03T19:50:01+00:00") == 0.02
    assert len(events) == 1


@pytest.mark.parametrize("case", ["entry", "exit", "leg"])
def test_the_intraday_sync_never_books_a_fill_price_that_is_not_one(case):
    """QA-Ops on #545, moved by M10 1.19 (#444) to engine/intraday.IntradayEngine._sync_positions: an entry, an exit
    or a bracket leg whose filled_avg_price is not a finite number above zero is not booked (read again at the next
    sync) and raises the refusal; the same position with a good price is booked."""
    from types import SimpleNamespace

    from kaibot.engine.intraday import IntradayEngine

    def run(px):
        booked, refused = [], []
        o = {"id": "o1", "status": "filled", "qty": "10", "filled_qty": "10", "filled_avg_price": px}
        if case == "leg":
            o = {"id": "o1", "status": "accepted", "qty": "10", "filled_qty": "0", "legs": [
                {"id": "l1", "status": "filled", "type": "stop", "qty": "10", "filled_qty": "10",
                 "filled_avg_price": px}]}
        p = SimpleNamespace(status="pending" if case == "entry" else "open", symbol="A", order_id="o1",
                            exit_order_id="o1" if case == "exit" else None, exit_reason="time", armed=False)
        fake = SimpleNamespace(pos={"A": p}, broker=SimpleNamespace(order=lambda oid: o),
                               _payload_refused=lambda key, why: refused.append(why),
                               _on_entry_fill=lambda p, o: booked.append(("entry", o["filled_avg_price"])),
                               _on_exit_fill=lambda p, px, *a: booked.append(("exit", px)),
                               _close_trade=lambda *a: booked.append("closed"))
        IntradayEngine._sync_positions(fake)
        return booked, refused

    for bad in ("NaN", "-1", "0", None, "inf"):
        booked, refused = run(bad)
        assert booked == [] and len(refused) == 1, (bad, booked, refused)
    booked, refused = run("100.5")
    assert refused == [] and len(booked) == 1
